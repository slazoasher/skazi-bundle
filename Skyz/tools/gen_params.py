# Regenerates Source/Params.h from tools/params.json (dumped from web/index.html: dumpParams()).
import json, os
here = os.path.dirname(os.path.abspath(__file__))
ps = json.load(open(os.path.join(here, 'params.json')))
out = ['// GENERATED by tools/gen_params.py from tools/params.json (= dumpParams() in web/index.html). Do not edit.',
       '#pragma once', 'namespace skyz', '{',
       '    struct ParamDef { const char* id; float def; int steps; }; // steps 0 = continuous, 2 = switch, n = choice',
       '    enum ParamIndex', '    {']
out += ['        P_%s,' % p[0] for p in ps]
out += ['        NUM_PARAMS', '    };', '    inline const ParamDef paramDefs[NUM_PARAMS] {']
out += ['        { "%s", %sf, %d },' % (p[0], repr(float(p[1])), p[2]) for p in ps]
out += ['    };', '}', '']
open(os.path.join(here, '..', 'Source', 'Params.h'), 'w', newline='\n').write('\n'.join(out))
print(len(ps), 'params')
